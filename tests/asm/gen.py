"""Regenerates tests/cortex_programs.inc from tests/asm/*.s.

Usage (from the repo root):  py tests/asm/gen.py
Needs arm-none-eabi-as/objcopy (third_party/toolchain/bin or PATH).
"""
import glob
import os
import shutil
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOOLS = os.path.join(ROOT, 'third_party', 'toolchain', 'bin')


def tool(name):
    local = os.path.join(TOOLS, name + ('.exe' if os.name == 'nt' else ''))
    return local if os.path.exists(local) else shutil.which(name)


def main():
    out = ['// Generated by tests/asm/gen.py from tests/asm/*.s - do not edit by hand.', '']
    tmp = tempfile.mkdtemp()
    for src in sorted(glob.glob(os.path.join(ROOT, 'tests', 'asm', '*.s'))):
        n = os.path.splitext(os.path.basename(src))[0]
        obj, binf = os.path.join(tmp, n + '.o'), os.path.join(tmp, n + '.bin')
        subprocess.check_call([tool('arm-none-eabi-as'), src, '-o', obj])
        subprocess.check_call([tool('arm-none-eabi-objcopy'), '-O', 'binary', obj, binf])
        data = open(binf, 'rb').read()
        if len(data) % 2:
            data += b'\0'
        code = data[0x100:]
        hw = [code[i] | (code[i + 1] << 8) for i in range(0, len(code), 2)]
        name = ''.join(w.capitalize() for w in n.split('_'))
        out.append(f'// {n}.s: Thumb code placed at flash offset 0x100 (after the vector table).')
        out.append(f'const std::vector<uint16_t> k{name} = {{')
        for i in range(0, len(hw), 12):
            out.append('    ' + ', '.join(f'0x{h:04X}' for h in hw[i:i + 12]) + ',')
        out.append('};')
        out.append('')
    with open(os.path.join(ROOT, 'tests', 'cortex_programs.inc'), 'w', newline='\n') as f:
        f.write('\n'.join(out))


if __name__ == '__main__':
    main()
